// MARK: - Persistent container

final class PersistenceController {
    static let shared = PersistenceController()

    let container: NSPersistentContainer

    init(inMemory: Bool = false) {
        let model = PersistenceController.makeModel()
        container = NSPersistentContainer(name: "HeartRate", managedObjectModel: model)
        if inMemory {
            container.persistentStoreDescriptions.first?.url = URL(fileURLWithPath: "/dev/null")
        } else {
            container.persistentStoreDescriptions.first?.setOption(true as NSNumber,
                                                                    forKey: NSMigratePersistentStoresAutomaticallyOption)
            container.persistentStoreDescriptions.first?.setOption(true as NSNumber,
                                                                    forKey: NSInferMappingModelAutomaticallyOption)
        }
        container.loadPersistentStores { _, error in
            if let error {
                assertionFailure("Core Data store failed to load: \(error)")
            }
        }
        container.viewContext.automaticallyMergesChangesFromParent = true
        container.viewContext.mergePolicy = NSMergeByPropertyObjectTrumpMergePolicy
    }

    var context: NSManagedObjectContext { container.viewContext }

    func save() {
        guard context.hasChanges else { return }
        do {
            try context.save()
        } catch {
            context.rollback()
            assertionFailure("Core Data save failed: \(error)")
        }
    }

    // MARK: Model construction

    private static func makeModel() -> NSManagedObjectModel {
        let model = NSManagedObjectModel()

        func attr(_ name: String, _ type: NSAttributeType,
                  optional: Bool = false, defaultValue: Any? = nil,
                  unique: Bool = false) -> NSAttributeDescription {
            let a = NSAttributeDescription()
            a.name = name
            a.attributeType = type
            a.isOptional = optional
            a.isIndexed = unique
            a.defaultValue = defaultValue
            return a
        }

        func entity(_ name: String, _ className: String, _ attributes: [NSAttributeDescription]) -> NSEntityDescription {
            let e = NSEntityDescription()
            e.name = name
            e.managedObjectClassName = className
            e.properties = attributes
            return e
        }

        let measurement = entity("HeartRateMeasurementMO", "HeartRateMeasurementMO", [
            attr("id", .stringAttributeType, unique: true),
            attr("time", .dateAttributeType),
            attr("type", .stringAttributeType),
            attr("value", .doubleAttributeType, defaultValue: 0),
            attr("tagId", .stringAttributeType, optional: true),
            attr("createdAt", .dateAttributeType),
            attr("pulse", .doubleAttributeType, defaultValue: 0),
            attr("hrv", .doubleAttributeType, defaultValue: 0),
            attr("rmssd", .doubleAttributeType, defaultValue: 0),
            attr("sdnn", .doubleAttributeType, defaultValue: 0),
            attr("pnn50", .doubleAttributeType, defaultValue: 0),
            attr("stress", .doubleAttributeType, defaultValue: 0),
            attr("energy", .doubleAttributeType, defaultValue: 0),
            attr("healthIndex", .doubleAttributeType, defaultValue: 0),
            attr("csi", .doubleAttributeType, defaultValue: 0),
            attr("healthKitID", .stringAttributeType, optional: true),
            attr("source", .stringAttributeType, defaultValue: "inApp"),
            attr("isTagAutoGenerated", .booleanAttributeType, defaultValue: false),
            attr("hasReadAIComment", .booleanAttributeType, defaultValue: false)
        ])
        measurement.uniquenessConstraints = [["id"]]

        let customTag = entity("CustomTagMO", "CustomTagMO", [
            attr("id", .stringAttributeType, unique: true),
            attr("name", .stringAttributeType),
            attr("colorName", .stringAttributeType),
            attr("cluster", .stringAttributeType, defaultValue: "general"),
            attr("createdAt", .stringAttributeType)
        ])
        customTag.uniquenessConstraints = [["id"]]

        let pressure = entity("PressureLogMO", "PressureLogMO", [
            attr("id", .stringAttributeType, unique: true),
            attr("tagId", .stringAttributeType, optional: true),
            attr("sys", .integer32AttributeType, defaultValue: 0),
            attr("dia", .integer32AttributeType, defaultValue: 0),
            attr("createdAt", .dateAttributeType)
        ])
        pressure.uniquenessConstraints = [["id"]]

        let oxygen = entity("OxygenLogMO", "OxygenLogMO", [
            attr("id", .stringAttributeType, unique: true),
            attr("tagId", .stringAttributeType, optional: true),
            attr("value", .integer32AttributeType, defaultValue: 0),
            attr("createdAt", .dateAttributeType)
        ])
        oxygen.uniquenessConstraints = [["id"]]

        let glucose = entity("GlucoseLogMO", "GlucoseLogMO", [
            attr("id", .stringAttributeType, unique: true),
            attr("tagId", .stringAttributeType, optional: true),
            attr("value", .doubleAttributeType, defaultValue: 0),
            attr("createdAt", .dateAttributeType)
        ])
        glucose.uniquenessConstraints = [["id"]]

        let reminder = entity("ReminderMO", "ReminderMO", [
            attr("time", .dateAttributeType),
            attr("type", .stringAttributeType)
        ])

        let achievement = entity("AchievementTierProgressMO", "AchievementTierProgressMO", [
            attr("achievementType", .stringAttributeType),
            attr("rewardValue", .integer32AttributeType, defaultValue: 0)
        ])

        let level = entity("JourneyLevelProgressMO", "JourneyLevelProgressMO", [
            attr("levelId", .stringAttributeType),
            attr("startedAt", .dateAttributeType)
        ])

        let task = entity("JourneyTaskProgressMO", "JourneyTaskProgressMO", [
            attr("taskId", .stringAttributeType),
            attr("currentValue", .integer64AttributeType, defaultValue: 0),
            attr("targetValue", .integer64AttributeType, defaultValue: 0),
            attr("category", .stringAttributeType, defaultValue: "any_measures_vol"),
            attr("type", .stringAttributeType, defaultValue: "core"),
            attr("referenceId", .stringAttributeType, optional: true),
            attr("readComments", .stringAttributeType, optional: true),
            attr("completedAt", .dateAttributeType, optional: true)
        ])
        task.uniquenessConstraints = [["taskId"]]

        let levelTasks = NSRelationshipDescription()
        levelTasks.name = "tasks"
        levelTasks.destinationEntity = task
        levelTasks.minCount = 0
        levelTasks.maxCount = 0
        levelTasks.deleteRule = .cascadeDeleteRule
        levelTasks.isOptional = true

        let taskLevel = NSRelationshipDescription()
        taskLevel.name = "level"
        taskLevel.destinationEntity = level
        taskLevel.minCount = 0
        taskLevel.maxCount = 1
        taskLevel.deleteRule = .nullifyDeleteRule
        taskLevel.isOptional = true

        levelTasks.inverseRelationship = taskLevel
        taskLevel.inverseRelationship = levelTasks
        level.properties.append(levelTasks)
        task.properties.append(taskLevel)

        let synced = entity("SyncedHealthKitRecordMO", "SyncedHealthKitRecordMO", [
            attr("syncedAt", .dateAttributeType),
            attr("healthKitID", .stringAttributeType),
            attr("recordType", .stringAttributeType)
        ])

        model.entities = [measurement, customTag, pressure, oxygen, glucose, reminder,
                          achievement, level, task, synced]
        return model
    }
}
