import CoreData
import Foundation

@MainActor
final class HealthDataStore: ObservableObject {
    static let shared = HealthDataStore()

    let container: NSPersistentContainer
    @Published private(set) var revision = 0

    private var context: NSManagedObjectContext { container.viewContext }

    init(container: NSPersistentContainer = PersistenceController.shared.container) {
        self.container = container
    }

    private func bump() {
        revision &+= 1
    }

    // MARK: - Heart rate measurements

    func measurements(limit: Int? = nil) -> [HRMeasurement] {
        let request = NSFetchRequest<HeartRateMeasurementMO>(entityName: "HeartRateMeasurementMO")
        request.sortDescriptors = [NSSortDescriptor(key: "time", ascending: false)]
        if let limit { request.fetchLimit = limit }
        return (try? context.fetch(request))?.map(Self.domain(from:)) ?? []
    }

    func measurements(from start: Date, to end: Date) -> [HRMeasurement] {
        let request = NSFetchRequest<HeartRateMeasurementMO>(entityName: "HeartRateMeasurementMO")
        request.sortDescriptors = [NSSortDescriptor(key: "time", ascending: false)]
        request.predicate = NSPredicate(format: "time >= %@ AND time < %@", start as NSDate, end as NSDate)
        return (try? context.fetch(request))?.map(Self.domain(from:)) ?? []
    }

    func measurement(id: String) -> HRMeasurement? {
        let request = NSFetchRequest<HeartRateMeasurementMO>(entityName: "HeartRateMeasurementMO")
        request.predicate = NSPredicate(format: "id == %@", id)
        request.fetchLimit = 1
        return (try? context.fetch(request))?.first.map(Self.domain(from:))
    }

    @discardableResult
    func addHeartMeasurement(_ derived: DerivedMetrics,
                             kind: MeasurementKind,
                             tagId: String? = nil,
                             time: Date = Date(),
                             source: String = "inApp") -> HRMeasurement {
        let mo = HeartRateMeasurementMO(context: context)
        mo.id = UUID().uuidString
        mo.time = time
        mo.createdAt = Date()
        mo.type = kind.rawValue
        mo.value = derived.pulse
        mo.tagId = tagId
        mo.pulse = derived.pulse
        mo.hrv = derived.sdnn
        mo.rmssd = derived.rmssd
        mo.sdnn = derived.sdnn
        mo.pnn50 = derived.pnn50
        mo.stress = derived.stress
        mo.energy = derived.energy
        mo.healthIndex = derived.healthIndex
        mo.csi = derived.csi
        mo.source = source
        mo.isTagAutoGenerated = false
        mo.hasReadAIComment = false
        save()
        return Self.domain(from: mo)
    }

    /// Manual "Log Measure" entry (camera and manual entries share the entity, §2.1).
    @discardableResult
    func addManualHeartRate(pulse: Int, tagId: String?, time: Date = Date()) -> HRMeasurement {
        let derived = DerivedMetrics(pulse: Double(pulse), sdnn: 0, rmssd: 0, pnn50: 0,
                                     stress: 0, energy: 0, healthIndex: 0, csi: 0)
        return addHeartMeasurement(derived, kind: .manual, tagId: tagId, time: time)
    }

    func setTag(measurementID: String, tagId: String?) {
        guard let mo = fetchMeasurementMO(id: measurementID) else { return }
        guard mo.tagId != tagId else { return }
        mo.tagId = tagId
        save()
    }

    func deleteMeasurement(id: String) {
        guard let mo = fetchMeasurementMO(id: id) else { return }
        context.delete(mo)
        save()
    }

    private func fetchMeasurementMO(id: String) -> HeartRateMeasurementMO? {
        let request = NSFetchRequest<HeartRateMeasurementMO>(entityName: "HeartRateMeasurementMO")
        request.predicate = NSPredicate(format: "id == %@", id)
        request.fetchLimit = 1
        return try? context.fetch(request).first
    }

    // MARK: - Blood pressure / oxygen / glucose

    func pressureRecords() -> [PressureRecord] {
        let request = NSFetchRequest<PressureLogMO>(entityName: "PressureLogMO")
        request.sortDescriptors = [NSSortDescriptor(key: "createdAt", ascending: false)]
        return (try? context.fetch(request))?.map {
            PressureRecord(id: $0.id, tagId: $0.tagId, sys: $0.sys, dia: $0.dia, createdAt: $0.createdAt)
        } ?? []
    }

    func oxygenRecords() -> [OxygenRecord] {
        let request = NSFetchRequest<OxygenLogMO>(entityName: "OxygenLogMO")
        request.sortDescriptors = [NSSortDescriptor(key: "createdAt", ascending: false)]
        return (try? context.fetch(request))?.map {
            OxygenRecord(id: $0.id, tagId: $0.tagId, value: $0.value, createdAt: $0.createdAt)
        } ?? []
    }

    func glucoseRecords() -> [GlucoseRecord] {
        let request = NSFetchRequest<GlucoseLogMO>(entityName: "GlucoseLogMO")
        request.sortDescriptors = [NSSortDescriptor(key: "createdAt", ascending: false)]
        return (try? context.fetch(request))?.map {
            GlucoseRecord(id: $0.id, tagId: $0.tagId, value: $0.value, createdAt: $0.createdAt)
        } ?? []
    }

    func addPressure(sys: Int, dia: Int, tagId: String?, time: Date = Date()) {
        let mo = PressureLogMO(context: context)
        mo.id = UUID().uuidString
        mo.sys = sys
        mo.dia = dia
        mo.tagId = tagId
        mo.createdAt = time
        save()
    }

    func addOxygen(value: Int, tagId: String?, time: Date = Date()) {
        let mo = OxygenLogMO(context: context)
        mo.id = UUID().uuidString
        mo.value = value
        mo.tagId = tagId
        mo.createdAt = time
        save()
    }

    func addGlucose(value: Double, tagId: String?, time: Date = Date()) {
        let mo = GlucoseLogMO(context: context)
        mo.id = UUID().uuidString
        mo.value = value
        mo.tagId = tagId
        mo.createdAt = time
        save()
    }

    func deletePressure(id: String) {
        deleteEntity(named: "PressureLogMO", id: id)
    }

    func deleteOxygen(id: String) {
        deleteEntity(named: "OxygenLogMO", id: id)
    }

    func deleteGlucose(id: String) {
        deleteEntity(named: "GlucoseLogMO", id: id)
    }

    func setTag(entityName: String, id: String, tagId: String?) {
        let request = NSFetchRequest<NSManagedObject>(entityName: entityName)
        request.predicate = NSPredicate(format: "id == %@", id)
        request.fetchLimit = 1
        guard let object = try? context.fetch(request).first else { return }
        object.setValue(tagId, forKey: "tagId")
        save()
    }

    private func deleteEntity(named name: String, id: String) {
        let request = NSFetchRequest<NSManagedObject>(entityName: name)
        request.predicate = NSPredicate(format: "id == %@", id)
        request.fetchLimit = 1
        guard let object = try? context.fetch(request).first else { return }
        context.delete(object)
        save()
    }

    // MARK: - Custom tags

    func customTags() -> [CustomTag] {
        let request = NSFetchRequest<CustomTagMO>(entityName: "CustomTagMO")
        request.sortDescriptors = [NSSortDescriptor(key: "createdAt", ascending: true)]
        return (try? context.fetch(request))?.map {
            CustomTag(id: $0.id, name: $0.name, colorName: $0.colorName,
                      cluster: $0.cluster, createdAt: $0.createdAt)
        } ?? []
    }

    func createCustomTag(name: String, colorName: String, cluster: String) {
        guard customTags().count < 20 else { return }
        let mo = CustomTagMO(context: context)
        mo.id = UUID().uuidString
        mo.name = String(name.prefix(30))
        mo.colorName = colorName
        mo.cluster = cluster
        mo.createdAt = ISO8601DateFormatter().string(from: Date())
        save()
    }

    func updateCustomTag(id: String, name: String, colorName: String, cluster: String) {
        let request = NSFetchRequest<CustomTagMO>(entityName: "CustomTagMO")
        request.predicate = NSPredicate(format: "id == %@", id)
        request.fetchLimit = 1
        guard let mo = try? context.fetch(request).first else { return }
        mo.name = String(name.prefix(30))
        mo.colorName = colorName
        mo.cluster = cluster
        save()
    }

    func deleteCustomTag(id: String) {
        let request = NSFetchRequest<CustomTagMO>(entityName: "CustomTagMO")
        request.predicate = NSPredicate(format: "id == %@", id)
        request.fetchLimit = 1
        guard let mo = try? context.fetch(request).first else { return }
        context.delete(mo)
        save()
    }

    // MARK: - Reminders

    func reminders() -> [Reminder] {
        let request = NSFetchRequest<ReminderMO>(entityName: "ReminderMO")
        request.sortDescriptors = [NSSortDescriptor(key: "time", ascending: true)]
        return (try? context.fetch(request))?.map {
            Reminder(id: "\($0.objectID.uriRepresentation().absoluteString)", time: $0.time, type: $0.type)
        } ?? []
    }

    func addReminder(time: Date, type: String) {
        let mo = ReminderMO(context: context)
        mo.time = time
        mo.type = type
        save()
    }

    func deleteReminder(id: String) {
        let request = NSFetchRequest<ReminderMO>(entityName: "ReminderMO")
        guard let reminders = try? context.fetch(request) else { return }
        for reminder in reminders where "\(reminder.objectID.uriRepresentation().absoluteString)" == id {
            context.delete(reminder)
        }
        save()
    }

    // MARK: - Achievement / journey progress

    func achievementRewards() -> [String: Int] {
        let request = NSFetchRequest<AchievementTierProgressMO>(entityName: "AchievementTierProgressMO")
        let items = (try? context.fetch(request)) ?? []
        var result: [String: Int] = [:]
        for item in items {
            result[item.achievementType] = max(result[item.achievementType] ?? 0, item.rewardValue)
        }
        return result
    }

    func setAchievementReward(type: String, reward: Int) {
        let request = NSFetchRequest<AchievementTierProgressMO>(entityName: "AchievementTierProgressMO")
        request.predicate = NSPredicate(format: "achievementType == %@ AND rewardValue == %d", type, reward)
        if let existing = try? context.fetch(request).first {
            existing.rewardValue = reward
        } else {
            let mo = AchievementTierProgressMO(context: context)
            mo.achievementType = type
            mo.rewardValue = reward
        }
        save()
    }

    func journeyTaskProgress() -> [String: (current: Int64, target: Int64, completedAt: Date?)] {
        let request = NSFetchRequest<JourneyTaskProgressMO>(entityName: "JourneyTaskProgressMO")
        let items = (try? context.fetch(request)) ?? []
        var result: [String: (Int64, Int64, Date?)] = [:]
        for item in items {
            result[item.taskId] = (item.currentValue, item.targetValue, item.completedAt)
        }
        return result
    }

    func updateJourneyTask(taskId: String, current: Int64, target: Int64, category: String,
                           type: String, referenceId: String?, completed: Bool) {
        let request = NSFetchRequest<JourneyTaskProgressMO>(entityName: "JourneyTaskProgressMO")
        request.predicate = NSPredicate(format: "taskId == %@", taskId)
        request.fetchLimit = 1
        let mo = (try? context.fetch(request).first) ?? JourneyTaskProgressMO(context: context)
        if mo.isInserted {
            mo.taskId = taskId
            mo.category = category
            mo.type = type
            mo.referenceId = referenceId
        }
        mo.currentValue = current
        mo.targetValue = target
        if completed, mo.completedAt == nil { mo.completedAt = Date() }
        save()
    }

    // MARK: - Save

    func save() {
        PersistenceController.shared.save()
        bump()
    }

    // MARK: - Mapping

    static func domain(from mo: HeartRateMeasurementMO) -> HRMeasurement {
        HRMeasurement(id: mo.id,
                      time: mo.time,
                      kind: MeasurementKind(rawValue: mo.type) ?? .camera,
                      tagId: mo.tagId,
                      createdAt: mo.createdAt,
                      pulse: mo.pulse,
                      hrv: mo.hrv,
                      rmssd: mo.rmssd,
                      sdnn: mo.sdnn,
                      pnn50: mo.pnn50,
                      stress: mo.stress,
                      energy: mo.energy,
                      healthIndex: mo.healthIndex,
                      csi: mo.csi,
                      source: mo.source)
    }

    // MARK: - Developer sample data (Debug only)

    func seedDemoData() {
        let calendar = Calendar.current
        let custom = customTags()
        if custom.isEmpty {
            createCustomTag(name: "Morning Run", colorName: "green", cluster: "stress")
            createCustomTag(name: "Coffee", colorName: "orange", cluster: "food")
        }
        let tags = customTags().map(\.id)
        var rng = SystemRandomNumberGenerator()
        for dayOffset in stride(from: 13, through: 0, by: -1) {
            guard let day = calendar.date(byAdding: .day, value: -dayOffset, to: Date()) else { continue }
            let count = Int.random(in: 1...2, using: &rng)
            for index in 0..<count {
                let hour = [9, 18, 21][index % 3]
                guard let time = calendar.date(bySettingHour: hour, minute: Int.random(in: 0...59, using: &rng),
                                               second: 0, of: day) else { continue }
                let pulse = Double(Int.random(in: 62...88, using: &rng))
                let rmssd = Double.random(in: 32...68, using: &rng)
                let sdnn = Double.random(in: 42...86, using: &rng)
                let pnn50 = Double.random(in: 6...28, using: &rng)
                let energy = clamp(sdnn / 100 * 120, 0, 120)
                let stress = clamp(100 - sdnn, 0, 100)
                let health = clamp(sdnn / 10, 0, 10)
                let derived = DerivedMetrics(pulse: pulse.rounded(), sdnn: sdnn.rounded(), rmssd: rmssd.rounded(),
                                             pnn50: pnn50.rounded(), stress: stress.rounded(),
                                             energy: energy.rounded(), healthIndex: (health * 10).rounded() / 10,
                                             csi: Double(Int.random(in: 60...240, using: &rng)))
                addHeartMeasurement(derived, kind: .camera,
                                    tagId: tags.isEmpty ? nil : tags[Int.random(in: 0..<tags.count, using: &rng)],
                                    time: time)
            }
        }
        // Latest measurement should look fresh for Home.
        if let latest = calendar.date(bySettingHour: 9, minute: 12, second: 0, of: Date()) {
            addHeartMeasurement(DerivedMetrics(pulse: 72, sdnn: 58, rmssd: 44, pnn50: 18,
                                              stress: 42, energy: 81, healthIndex: 6.2, csi: 121),
                                kind: .camera, tagId: tags.first, time: min(latest, Date()))
        }
        let now = Date()
        for offset in 0..<3 {
            let date = calendar.date(byAdding: .day, value: -offset * 2, to: now) ?? now
            addPressure(sys: [118, 124, 121][offset], dia: [76, 79, 77][offset],
                        tagId: tags.first, time: date)
            addOxygen(value: [98, 97, 99][offset], tagId: nil, time: date)
            addGlucose(value: [97.0, 110.0, 104.0][offset], tagId: nil, time: date)
        }
    }

    func resetAllData() {
        for entity in container.managedObjectModel.entities {
            guard let name = entity.name else { continue }
            let request = NSFetchRequest<NSFetchRequestResult>(entityName: name)
            let delete = NSBatchDeleteRequest(fetchRequest: request)
            delete.resultType = .resultTypeObjectIDs
            if let result = try? context.execute(delete) as? NSBatchDeleteResult,
               let ids = result.result as? [NSManagedObjectID] {
                let changes = [NSDeletedObjectsKey: ids]
                NSManagedObjectContext.mergeChanges(fromRemoteContextSave: changes, into: [context])
            }
        }
        save()
    }
}

// MARK: - Date ranges

enum DateRange {
    static func day(containing date: Date) -> (start: Date, end: Date) {
        let calendar = Calendar.current
        let start = calendar.startOfDay(for: date)
        return (start, calendar.date(byAdding: .day, value: 1, to: start) ?? date)
    }

    static func startOfWeek(_ date: Date = Date()) -> Date {
        let calendar = Calendar.current
        return calendar.dateInterval(of: .weekOfYear, for: date)?.start ?? date
    }

    static func startOfMonth(_ date: Date = Date()) -> Date {
        let calendar = Calendar.current
        return calendar.dateInterval(of: .month, for: date)?.start ?? date
    }

    static func monthsAgo(_ count: Int) -> Date {
        Calendar.current.date(byAdding: .month, value: -count, to: Date()) ?? Date()
    }
}
